// Run dispatches native commands through urfave/cli and unknown top-level
// command names to executable extensions.
func Run(ctx context.Context, args []string) error {
	if ctx == nil {
		ctx = context.Background()
	}
	if len(args) < 2 {
		return RootCmd.Run(ctx, args)
	}
	name, _, isCommand := topLevelCommand(args[1:])
	if !isCommand || !extensions.ValidName(name) || hasNativeCommand(name) {
		return runNative(ctx, args, name)
	}
	if name == "help" || name == "version" {
		return RootCmd.Run(ctx, args)
	}
	return runExtension(ctx, args, name)
}

// runNative catches errors that happen before a machine command's Action can
// format them (for example, unknown flags). Writers are buffered so usage help
// generated by urfave/cli can be moved to stderr when JSON was requested.
func runNative(ctx context.Context, args []string, name string) error {
	if !requestsMachineOutput(args, name) {
		return RootCmd.Run(ctx, args)
	}
	var stdout bytes.Buffer
	var stderr bytes.Buffer
	writerState := setCommandWriters(RootCmd, &stdout, &stderr)
	defer writerState.restore()
	err := RootCmd.Run(ctx, args)
	if err == nil {
		_, writeErr := io.Copy(writerState.stdout, &stdout)
		if writeErr == nil {
			_, writeErr = io.Copy(writerState.stderr, &stderr)
		}
		return writeErr
	}
	if IsReported(err) {
		_, _ = io.Copy(writerState.stderr, &stderr)
		return err
	}
	// Parser diagnostics and generated help are not valid machine output.
	fmt.Fprintln(writerState.stderr, string(output.MarshalError("command_failed", err)))
	return machineError{err}
}

func requestsMachineOutput(args []string, command string) bool {
	switch command {
	case "predict", "report", "passes":
	default:
		return false
	}
	for i := 2; i < len(args); i++ {
		if args[i] == "--" {
			return false
		}
		if args[i] == "--format=json" {
			return true
		}
		if args[i] == "--format" && i+1 < len(args) && args[i+1] == "json" {
			return true
		}
	}
	return false
}

type commandWriterState struct {
	commands   []*cli.Command
	writers    []io.Writer
	errWriters []io.Writer
	stdout     io.Writer
	stderr     io.Writer
}

func setCommandWriters(root *cli.Command, writer, errWriter io.Writer) *commandWriterState {
	state := &commandWriterState{stdout: root.Writer, stderr: root.ErrWriter}
	if state.stdout == nil {
		state.stdout = os.Stdout
	}
	if state.stderr == nil {
		state.stderr = os.Stderr
	}
	var visit func(*cli.Command)
	visit = func(c *cli.Command) {
		state.commands = append(state.commands, c)
		oldWriter, oldErrWriter := c.Writer, c.ErrWriter
		if oldWriter == nil {
			oldWriter = os.Stdout
		}
		if oldErrWriter == nil {
			oldErrWriter = os.Stderr
		}
		state.writers = append(state.writers, oldWriter)
		state.errWriters = append(state.errWriters, oldErrWriter)
		c.Writer = writer
		c.ErrWriter = errWriter
		for _, child := range c.Commands {
			visit(child)
		}
	}
	visit(root)
	return state
}

func (s *commandWriterState) restore() {
	for i, c := range s.commands {
		c.Writer = s.writers[i]
	}
	for i, c := range s.commands {
		c.ErrWriter = s.errWriters[i]
	}
}

// topLevelCommand finds the first positional token. Root currently has no
// global flags, but recognizes cli's standard help and version switches here.
func topLevelCommand(args []string) (name string, separator bool, ok bool) {
	for len(args) > 0 {
		a := args[0]
		if a == "--" {
			if len(args) < 2 {
				return "", true, false
			}
			return args[1], true, true
		}
		if a == "--help" || a == "-h" || a == "--version" || a == "-v" {
			return "", false, false
		}
		if strings.HasPrefix(a, "-") {
			return "", false, false
		}
		return a, false, true
	}
	return "", false, false
}

func hasNativeCommand(name string) bool {
	for _, command := range RootCmd.Commands {
		if command.Name == name {
			return true
		}
		for _, alias := range command.Aliases {
			if alias == name {
				return true
			}
		}
	}
	return false
}

func runExtension(ctx context.Context, args []string, name string) error {
	// Locate command name's original position and preserve every later token.
	idx := -1
	for i := 1; i < len(args); i++ {
		if args[i] == name {
			idx = i
			break
		}
	}
	if idx < 0 {
		return fmt.Errorf("invalid extension invocation")
	}
	// With terminal input the child stays in the foreground process group, so
	// Ctrl+C reaches both processes. Absorb it in tlego, allow the child to handle
	// it and reap normally, then force-cancel only if the child stays alive.
	if extensions.InteractiveInput(os.Stdin) {
		var stop context.CancelFunc
		ctx, stop = waitForInteractiveInterrupt(ctx)
		defer stop()
	} else {
		// For piped input, the parent owns Ctrl+C and cancels the isolated child tree.
		var stop context.CancelFunc
		ctx, stop = signal.NotifyContext(ctx, os.Interrupt)
		defer stop()
	}
	return extensions.Run(ctx, append([]string{name}, args[idx+1:]...), RootCmd.Version, os.Stdin, os.Stdout, os.Stderr)
}

func waitForInteractiveInterrupt(parent context.Context) (context.Context, context.CancelFunc) {
	ctx, cancel := context.WithCancel(parent)
	signals := make(chan os.Signal, 2)
	signal.Notify(signals, os.Interrupt)
	done := make(chan struct{})
	go func() {
		var timer *time.Timer
		defer func() {
			if timer != nil {
				timer.Stop()
			}
		}()
		var timerC <-chan time.Time
		interrupts := 0
		for {
			select {
			case <-done:
				return
			case <-ctx.Done():
				return
			case <-signals:
				interrupts++
				if interrupts > 1 {
					cancel()
					return
				}
				timer = time.NewTimer(2 * time.Second)
				timerC = timer.C
			case <-timerC:
				cancel()
				return
			}
		}
	}()
	return ctx, func() {
		close(done)
		signal.Stop(signals)
		cancel()
	}
}

// ExitCode reports the requested process status for extension errors.
func ExitCode(err error) (int, bool) {
	var exitErr *extensions.ExitError
	if errors.As(err, &exitErr) {
		return exitErr.Code, true
	}
	return 0, false
}

func IsReported(err error) bool {
	var reported interface{ Reported() bool }
	return errors.As(err, &reported) && reported.Reported()
}
