// Command notices writes THIRD_PARTY_NOTICES.md: the license text of every module
// compiled into khonsu, the copied SGP4 engine, the Go standard library and the
// bundled Three.js. Release archives ship the file, since most of these licenses
// require their notice to travel with binaries.
//
// Run from the repository root, after npm ci in internal/webui:
//
//	go run ./internal/tools/notices > THIRD_PARTY_NOTICES.md
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

// Modules whose published version carries no license file, with where the license is stated.
var missingLicense = map[string]string{
	"github.com/mattn/go-localereader": "This version ships no license file. The upstream repository, https://github.com/mattn/go-localereader, is published under the MIT License.",
}

type notice struct{ title, origin, text string }

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

func run() error {
	modules, err := binaryModules()
	if err != nil {
		return err
	}
	var notices []notice
	add := func(title, origin, path string) error {
		text, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		notices = append(notices, notice{title, origin, strings.TrimSpace(strings.ReplaceAll(string(text), "\r\n", "\n"))})
		return nil
	}
	if err := add("SGP4 engine (internal/sgp4)", "Copied from github.com/Mohammed-Ashour/go-satellite-v2", "internal/sgp4/LICENSE"); err != nil {
		return err
	}
	if err := add("Go standard library", "https://go.dev", filepath.Join(runtime.GOROOT(), "LICENSE")); err != nil {
		return err
	}
	if err := add("three.js", "Bundled in the web app (internal/webui/dist/app.js)", "internal/webui/node_modules/three/LICENSE"); err != nil {
		return fmt.Errorf("%w (run npm ci in internal/webui first)", err)
	}
	for _, m := range modules {
		if text, ok := missingLicense[m.path]; ok {
			notices = append(notices, notice{m.path + " " + m.version, "https://" + m.path, text})
			continue
		}
		file, err := licenseFile(m.dir)
		if err != nil {
			return fmt.Errorf("%s: %w", m.path, err)
		}
		if err := add(m.path+" "+m.version, "https://"+m.path, file); err != nil {
			return err
		}
	}

	out := bufio.NewWriter(os.Stdout)
	fmt.Fprint(out, "# Third-party notices\n\nKhonsu is MIT licensed (see LICENSE.md). Its binaries also contain the software below, under these licenses. Generated by `go run ./internal/tools/notices`; do not edit by hand.\n")
	for _, n := range notices {
		fmt.Fprintf(out, "\n## %s\n\n%s\n\n```text\n%s\n```\n", n.title, n.origin, n.text)
	}
	return out.Flush()
}

type module struct{ path, version, dir string }

// binaryModules lists the modules linked into a release binary, not test-only ones.
// Some, such as terminal support for Windows, are linked only on one platform, so
// it asks for every release target.
func binaryModules() ([]module, error) {
	seen := map[string]module{}
	for _, goos := range []string{"linux", "darwin", "windows"} {
		cmd := exec.Command("go", "list", "-deps", "-f", "{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}", ".")
		cmd.Env = append(os.Environ(), "CGO_ENABLED=0", "GOOS="+goos)
		output, err := cmd.Output()
		if err != nil {
			return nil, fmt.Errorf("go list for %s: %w", goos, err)
		}
		for _, line := range strings.Split(string(bytes.TrimSpace(output)), "\n") {
			if parts := strings.Split(line, "\t"); len(parts) == 3 {
				seen[parts[0]] = module{parts[0], parts[1], parts[2]}
			}
		}
	}
	modules := make([]module, 0, len(seen))
	for _, m := range seen {
		modules = append(modules, m)
	}
	sort.Slice(modules, func(i, j int) bool { return modules[i].path < modules[j].path })
	return modules, nil
}

func licenseFile(dir string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", err
	}
	for _, entry := range entries {
		name := strings.ToLower(entry.Name())
		if !entry.IsDir() && (strings.HasPrefix(name, "license") || strings.HasPrefix(name, "licence") || strings.HasPrefix(name, "copying")) {
			return filepath.Join(dir, entry.Name()), nil
		}
	}
	return "", fmt.Errorf("no license file in %s", dir)
}
